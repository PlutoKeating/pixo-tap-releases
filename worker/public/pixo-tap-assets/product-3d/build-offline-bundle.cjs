const fs = require('node:fs');
const path = require('node:path');

const productDir = __dirname;
const vendorDir = path.resolve(productDir, '..', 'vendor', 'three');

function read(filePath) {
  return fs.readFileSync(filePath, 'utf8').replace(/^\uFEFF/, '');
}

function exportProperties(source, objectName) {
  const match = source.match(/export\s*\{([\s\S]*?)\};?\s*$/);
  if (!match) throw new Error(`Missing final export block for ${objectName}.`);
  const properties = match[1].split(',').map(entry => {
    const value = entry.trim();
    const alias = value.match(/^(\S+)\s+as\s+(\S+)$/);
    return alias ? `${alias[2]}:${alias[1]}` : value;
  }).filter(Boolean);
  return { body: source.slice(0, match.index), properties };
}

function destructuringBindings(names) {
  return names.split(',').map(entry => {
    const value = entry.trim();
    const alias = value.match(/^(\S+)\s+as\s+(\S+)$/);
    return alias ? `${alias[1]}:${alias[2]}` : value;
  }).filter(Boolean).join(',');
}

function replaceNamedImport(source, modulePattern, objectName, errorLabel) {
  const pattern = new RegExp(`import\\s*\\{([\\s\\S]*?)\\}\\s*from\\s*['"]${modulePattern}['"];?`);
  if (!pattern.test(source)) throw new Error(`Missing ${errorLabel} named import.`);
  return source.replace(pattern, (_, names) => `const {${destructuringBindings(names)}} = ${objectName};`);
}

function objectFactory(source, objectName, spreads = []) {
  const { body, properties } = exportProperties(source, objectName);
  const entries = [...spreads.map(value => `...${value}`), ...properties];
  return `const ${objectName} = (() => {\n${body}\nreturn Object.freeze({${entries.join(',')}});\n})();\n`;
}

const threeCore = objectFactory(read(path.join(vendorDir, 'three.core.min.js')), 'THREE_CORE');

let threeModule = replaceNamedImport(
  read(path.join(vendorDir, 'three.module.min.js')),
  '\\.\\/three\\.core\\.min\\.js',
  'THREE_CORE',
  'Three.js core'
);
threeModule = threeModule.replace(
  /export\s*\{[\s\S]*?\}\s*from\s*['"]\.\/three\.core\.min\.js['"];?/,
  ''
);
if (/from\s*['"]\.\/three\.core\.min\.js['"]/.test(threeModule)) {
  throw new Error('A Three.js core module reference remains after conversion.');
}
const three = objectFactory(threeModule, 'THREE', ['THREE_CORE']);

let geometryUtils = replaceNamedImport(
  read(path.join(vendorDir, 'BufferGeometryUtils.js')),
  '\\.\\/three\\.module\\.min\\.js',
  'THREE',
  'Three.js'
);
geometryUtils = objectFactory(geometryUtils, 'BufferGeometryUtils');

let gltfLoader = replaceNamedImport(
  read(path.join(vendorDir, 'GLTFLoader.js')),
  '\\.\\/three\\.module\\.min\\.js',
  'THREE',
  'Three.js'
);
gltfLoader = gltfLoader.replace(
  /import\s*\{\s*toTrianglesDrawMode\s*\}\s*from\s*['"]\.\/BufferGeometryUtils\.js['"];?/,
  'const { toTrianglesDrawMode } = BufferGeometryUtils;'
);
gltfLoader = gltfLoader.replace(/export\s*\{\s*GLTFLoader\s*\};?\s*$/, '');
gltfLoader = `const GLTFLoader = (() => {\n${gltfLoader}\nreturn GLTFLoader;\n})();\n`;

let progress = read(path.join(productDir, 'product-3d-progress.mjs'));
progress = progress.replace(/\bexport\s+(?=function\s)/g, '');

let cameraLens = read(path.join(productDir, 'product-camera-lens.mjs'));
cameraLens = cameraLens.replace(/\bexport\s+(?=function\s)/g, '');

let interaction = read(path.join(productDir, 'product-3d-interaction.mjs'));
interaction = interaction
  .replace(/import\s+\*\s+as\s+THREE\s+from\s+['"][^'"]+['"];?\s*/, '')
  .replace(/import\s*\{\s*GLTFLoader\s*\}\s*from\s*['"][^'"]+['"];?\s*/, '')
  .replace(/import\s*\{\s*applyCameraLensTexture\s*\}\s*from\s*['"]\.\/product-camera-lens\.mjs[^'"]*['"];?\s*/, '')
  .replace(/import\s*\{[\s\S]*?\}\s*from\s*['"]\.\/product-3d-progress\.mjs[^'"]*['"];?\s*/, '')
  .replace(/\bexport\s+(?=(?:async\s+)?function\s)/g, '')
  .replace(
    'const source = new URL(stage.dataset.modelSrc, document.baseURI).href;',
    "const source = window.location.protocol === 'file:' ? PIXO_MODEL_DATA_URI : new URL(stage.dataset.modelSrc, document.baseURI).href;"
  );

if (!interaction.includes('PIXO_MODEL_DATA_URI')) {
  throw new Error('The offline model source replacement did not apply.');
}

const modelBase64 = fs.readFileSync(path.join(productDir, 'pixotap-red.glb')).toString('base64');
const banner = `/* PIXO TAP offline 3D bundle. Generated by build-offline-bundle.cjs. */\n`;
const bundle = `${banner}(() => {\n'use strict';\n${threeCore}\n${three}\n${geometryUtils}\n${gltfLoader}\n${cameraLens}\n${progress}\nconst PIXO_MODEL_DATA_URI = 'data:model/gltf-binary;base64,${modelBase64}';\n${interaction}\n})();\n`;

const outputPath = path.join(productDir, 'product-3d-offline.bundle.js');
fs.writeFileSync(outputPath, bundle, 'utf8');
console.log(`${outputPath}\t${Buffer.byteLength(bundle)} bytes`);
